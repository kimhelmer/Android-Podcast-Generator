package com.podcaststudio.app.domain

import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json

/** A web source. Only ever created from API-provided citations, never from model-written text. */
@Serializable
data class SourceRef(val title: String, val url: String)

@Serializable
data class ResearchResult(
    val topic: String,
    val language: Language,
    /** Fact notes in the episode language, with verified and unverified claims labelled. */
    val notes: String,
    val sources: List<SourceRef>,
    val researchedAt: Long,
    val model: String,
    val warnings: List<String> = emptyList(),
    /** Tokens OpenAI reported for this call (actual, not estimated). 0 when unknown. */
    val inputTokens: Int = 0,
    val outputTokens: Int = 0,
)

@Serializable
data class PodcastScript(
    val title: String,
    /** One or two sentences describing the episode; metadata, not spoken. */
    val summary: String,
    val language: Language,
    val segments: List<ScriptSegment>,
    /** Copied from the research stage, not generated by the script model. */
    val sources: List<SourceRef>,
    val researchedAt: Long,
    val generatedAt: Long,
    val researchModel: String,
    val scriptModel: String,
    val targetWords: Int,
    val estimatedDurationSeconds: Int,
    val warnings: List<String> = emptyList(),
    /** Tokens OpenAI reported for the script call(s), including a rewrite if one was needed. 0 when unknown. */
    val inputTokens: Int = 0,
    val outputTokens: Int = 0,
) {
    val wordCount: Int get() = segments.sumOf { it.text.wordCount() }
}

fun String.wordCount(): Int = trim().split(Regex("\\s+")).count { it.isNotEmpty() }

/** Research and script for an episode, persisted stage by stage. */
interface ContentRepository {
    suspend fun saveResearch(episodeId: String, research: ResearchResult)
    suspend fun saveScript(episodeId: String, script: PodcastScript)
    suspend fun getResearch(episodeId: String): ResearchResult?
    suspend fun getScript(episodeId: String): PodcastScript?
    suspend fun delete(episodeId: String)

    /** Saved when a run starts so an interrupted audio stage can be resumed later, even after the app restarts. */
    suspend fun saveRequest(episodeId: String, request: PodcastRequest)
    suspend fun getRequest(episodeId: String): PodcastRequest?

    /** Characters actually sent to text-to-speech for this episode, cumulative over retries. */
    suspend fun addTtsCharacters(episodeId: String, characters: Int)
    suspend fun getTtsCharacters(episodeId: String): Int

    /** Removes saved content of episodes that never finished and were last touched before [beforeMs]. */
    suspend fun purgeUnfinishedBefore(beforeMs: Long)

    /** Newest draft with a script and request but no finished episode, updated since [sinceMs]. */
    suspend fun latestUnfinished(sinceMs: Long): UnfinishedDraft?
}

val AppJson = Json {
    ignoreUnknownKeys = true
    encodeDefaults = true
}
